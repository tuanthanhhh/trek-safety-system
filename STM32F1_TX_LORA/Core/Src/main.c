/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_SPI1_Init();
  MX_I2C1_Init();

  lcd_init();

  /* Dòng 1 LCD: tiêu đề cố định */
  lcd_goto_XY(1, 0);
  lcd_send_string("===== TX_LORA =====");

  /* USER CODE BEGIN 2 */

  myLoRa = newLoRa();
  myLoRa.hSPIx                 = &hspi1;
  myLoRa.CS_port               = NSS_GPIO_Port;
  myLoRa.CS_pin                = NSS_Pin;
  myLoRa.reset_port            = RST_GPIO_Port;
  myLoRa.reset_pin             = RST_Pin;
  myLoRa.DIO0_port             = DIO0_GPIO_Port;
  myLoRa.DIO0_pin              = DIO0_Pin;
  
  myLoRa.frequency             = 433;
  myLoRa.spredingFactor        = SF_7;
  myLoRa.bandWidth             = BW_125KHz;
  myLoRa.crcRate               = CR_4_5;
  myLoRa.power                 = POWER_20db;          // Công suất max
  myLoRa.overCurrentProtection = 120;
  myLoRa.preamble              = 10;

  /* Reset phần cứng module LoRa */
  LoRa_reset(&myLoRa);

  /* Khởi tạo LoRa, hiển thị trạng thái lên dòng 2 LCD */
  lcd_goto_XY(2, 0);
  while (LoRa_init(&myLoRa) != LORA_OK)
  {
    lcd_send_string("LoRa INIT FAIL!   ");
  }
  lcd_send_string("LoRa INIT OK! ");
  LoRa_setSyncWord(&myLoRa, 0x12); // Đảm bảo SyncWord của 2 mạch giống hệt nhau
  
  // Bật AGC
  LoRa_write(&myLoRa, 0x26, 0x04);

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */
	  if (HAL_GetTick() - last_send_tick >= 500)
	  {
		  last_send_tick = HAL_GetTick();
		  send_count++;

		  char msg_buffer[20];
		  sprintf(msg_buffer, "*%lu#", (unsigned long)send_count);

		  uint8_t tx_result = LoRa_transmit(&myLoRa, (uint8_t*)msg_buffer, strlen(msg_buffer), 2000);

		  if (tx_result == 1)
		  {
			  HAL_GPIO_TogglePin(GPIOC, GPIO_PIN_13);

			  lcd_goto_XY(1, 0);
			  char tx_lcd[20];
			  snprintf(tx_lcd, sizeof(tx_lcd), "TX: %-12s", (char*)msg_buffer);
			  lcd_send_string(tx_lcd);

			  char lcd_line2[17];
			  snprintf(lcd_line2, sizeof(lcd_line2), "Cnt:%-5lu   OK  ", (unsigned long)send_count);
			  lcd_goto_XY(2, 0);
			  lcd_send_string(lcd_line2);
		  }
		  else
		  {
			  lcd_goto_XY(1, 0);
			  char tx_lcd[20];
			  snprintf(tx_lcd, sizeof(tx_lcd), "TX: %-12s", (char*)msg_buffer);
			  lcd_send_string(tx_lcd);

			  char lcd_line2[17];
			  snprintf(lcd_line2, sizeof(lcd_line2), "Cnt:%-5lu  FAIL ", (unsigned long)send_count);
			  lcd_goto_XY(2, 0);
			  lcd_send_string(lcd_line2);
		  }
	  }
    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

